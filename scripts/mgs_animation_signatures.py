#!/usr/bin/env python3
"""Extract complete retail animation-bytecode identities from the pinned decomp.

The renderer checks the entire bytecode, atlas layout and texture ID together.
An unfamiliar script is never classified from its texture alone.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / '.local/effects-research/mgs-upstream/source'
OUTPUT = ROOT / 'engine/ps1Runtime/src/games/mgs_animation_signatures.inc'
EXCLUDED = []


def extract():
    EXCLUDED.clear()
    codes = {m[1]: int(m[2], 16) for m in re.finditer(
        r'^#define\s+(PCX_\w+)\s+\(?\s*(0x[0-9A-Fa-f]+)',
        (SOURCE / 'include/strcode.h').read_text(), re.M)}
    result = []
    for path in sorted(SOURCE.rglob('*.c')):
        source = path.relative_to(SOURCE).as_posix()
        text = re.sub(r'/\*.*?\*/|//[^\n]*', '', path.read_text(), flags=re.S)
        arrays = {m[1]: bytes(int(v, 0) & 255 for v in m[2].split(',') if v.strip())
                  for m in re.finditer(r'\b(?:unsigned\s+)?char\s+(\w+)\[\s*\]\s*=\s*\{([\s,0-9a-fA-FxX]+)\};', text)}
        for m in re.finditer(r'\bANIMATION\s+(\w+)\s*=\s*\{(.*?)\};', text, re.S):
            fields = [v.strip() for v in m[2].split(',') if v.strip()]
            if len(fields) != 12:
                raise ValueError(f'{source}: unsupported ANIMATION {m[1]}')
            script = re.sub(r'\([^)]*\)', '', fields[-1]).strip()
            if script not in arrays:
                raise ValueError(f'{source}: missing script {script}')
            data = arrays[script]
            starts = [int.from_bytes(data[3+i*2:5+i*2], 'big') for i in range(data[2])]
            if not 0 < data[2] <= 4 or any(s < 3+2*len(starts) or s >= len(data) for s in starts):
                EXCLUDED.append(dict(source=source, symbol=m[1],
                                     reason='Decomp byte array has an out-of-bounds script directory'))
                continue
            texture = codes.get(fields[0])
            if texture is None:
                texture = int(fields[0], 0)
            # These are curated source identities. The selected profile is
            # subsequently emitted alongside FULL script bytes, never a
            # runtime heuristic based on a texture name or screen color.
            profile = {
                'PCX_SMOKE': 'Smoke', 'PCX_PCH_FOG': 'Smoke',
                'PCX_SOCOM_F': 'Muzzle', 'PCX_FA_FL10': 'Muzzle',
                'PCX_M60_FLASH': 'Muzzle', 'PCX_CANON_SEQ': 'Muzzle',
                'PCX_BOMB1_FL': 'Explosion', 'PCX_BLOOD_2': 'Blood',
                'PCX_SONIC': 'Ring', 'PCX_LENSE_FLARE1': 'Glow',
                'PCX_RCM_L': 'Glow', 'PCX_W_BONBORI': 'Glow',
                'PCX_B_MARK': 'Exclamation', 'PCX_Q_MARK': 'Question',
                'PCX_HEART': 'Heart', 'PCX_ZZZ': 'Sleep', 'PCX_HOSI': 'Star',
                'PCX_MAGAZIN': 'Debris', 'PCX_WT_SUD11': 'Debris',
            }.get(fields[0], 'Authored')
            if source == 'anime/effect/breath.c':
                # The second animation's urination attribution is unresolved.
                profile = 'Breath' if m[1] == 'anm_breath_form' else 'Authored'
            result.append(dict(source=source, symbol=m[1], script=script,
                               texture=texture, atlas=[int(v, 0) for v in fields[1:4]],
                               profile=profile, starts=starts, bytes=data.hex(),
                               sha256=hashlib.sha256(data).hexdigest()))
    return result


def generate(rows):
    out = ['// Generated by scripts/mgs_animation_signatures.py. Do not edit.',
           '// Full bytecode + atlas + texture are required for semantic attribution.']
    for i, row in enumerate(rows):
        out.append(f'// {row["source"]}: {row["symbol"]}')
        out.append(f'static constexpr uint8_t animationBytes{i}[] = {{' +
                   ','.join('0x'+row['bytes'][k:k+2] for k in range(0, len(row['bytes']), 2)) + '};')
    out.append('static constexpr AnimationSignature animationSignatures[] = {')
    for i, row in enumerate(rows):
        out.append('  {"%s", "%s", %d, {%s}, SurfaceKind::%s, animationBytes%d},' % (
            row['source'], row['symbol'], row['texture'], ','.join(map(str, row['atlas'])), row['profile'], i))
    return '\n'.join(out + ['};', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rows = extract()
    generated = generate(rows)
    manifest = json.dumps({'schema': 1, 'signatures': rows, 'excluded': EXCLUDED,
        'runtime_constructed': [{
            'source': 'kojo/sstorm.c', 'profile': 'SnowStorm',
            'program_hex': '001001000501fe0c000001ff080000000200010d0f',
            'mutable_byte_offsets': [8, 9], 'mutable_meaning': 'native lifetime',
            'textures': ['snow_ex1', 'snow_ex2', 'snow_ex3'], 'atlas': [1, 1, 1],
            'validation': 'All other program bytes, script start and cursor must match',
        }]}, indent=2) + '\n'
    targets = [(OUTPUT, generated), (ROOT / 'docs/mgs-animation-signatures.json', manifest)]
    for path, expected in targets:
        if args.check:
            if path.read_text() != expected:
                raise ValueError(f'Stale output: {path}')
        else:
            path.write_text(expected)
    print(f'{len(rows)} complete animation signatures')


if __name__ == '__main__':
    main()
