// Serialize full 1024x512 VRAM (ABGR1555) as a P6 PPM at `path`.
// Used by tools/smoke_test.py as the regression contract for game bring-up.
static bool dumpVramPpm(const ps1::gpu::GPU &gpu, const char *path) {
  std::FILE *f = std::fopen(path, "wb");
  if (!f) {
    fmt::print(stderr, "[VRAM-DUMP] open failed: {}\n", path);
    return false;
  }
  constexpr uint32_t W = ps1::gpu::GPU::VRAM_WIDTH;
  constexpr uint32_t H = ps1::gpu::GPU::VRAM_HEIGHT;
  std::fprintf(f, "P6\n%u %u\n255\n", W, H);
  const ps1::gpu::Color16 *vram = gpu.getVRAM();
  std::vector<uint8_t> row(W * 3);
  uint64_t nonZero = 0;
  for (uint32_t y = 0; y < H; ++y) {
    for (uint32_t x = 0; x < W; ++x) {
      uint16_t p = vram[y * W + x].raw;
      row[x * 3 + 0] = static_cast<uint8_t>((p & 0x1F) << 3);
      row[x * 3 + 1] = static_cast<uint8_t>(((p >> 5) & 0x1F) << 3);
      row[x * 3 + 2] = static_cast<uint8_t>(((p >> 10) & 0x1F) << 3);
      if (p != 0)
        ++nonZero;
    }
    std::fwrite(row.data(), 1, row.size(), f);
  }
  std::fclose(f);
  ps1::metrics::count("vram_dump.written");
  ps1::metrics::setState("vram_dump.nonzero_pixels",
                         static_cast<int64_t>(nonZero));
  fmt::print("[VRAM-DUMP] wrote {} ({}x{}), {} non-zero pixels\n", path, W, H,
             nonZero);
  return true;
}

// Serialize the immutable VBlank-latched modern display aperture. Unlike the
// native VRAM dump this is already cropped by the programmed GP1 display
// ranges and retains the configured internal scale and true-color samples.
// Donor comparison tools downsample and RGB5-quantize this PPM explicitly.
static bool dumpDisplayPpm(const ps1::gpu::GPU &gpu, const char *path) {
  std::vector<ps1::gpu::Color32> pixels;
  uint32_t width = 0;
  uint32_t height = 0;
  if (!gpu.copyDisplayRGBA8(pixels, width, height) || pixels.empty()) {
    fmt::print(stderr, "[DISPLAY-DUMP] modern display unavailable\n");
    return false;
  }

  std::FILE *f = std::fopen(path, "wb");
  if (!f) {
    fmt::print(stderr, "[DISPLAY-DUMP] open failed: {}\n", path);
    return false;
  }
  std::fprintf(f, "P6\n%u %u\n255\n", width, height);
  std::vector<uint8_t> row(static_cast<std::size_t>(width) * 3u);
  uint64_t nonBlack = 0;
  for (uint32_t y = 0; y < height; ++y) {
    for (uint32_t x = 0; x < width; ++x) {
      const ps1::gpu::Color32 color =
          pixels[static_cast<std::size_t>(y) * width + x];
      row[x * 3u + 0u] = color.r;
      row[x * 3u + 1u] = color.g;
      row[x * 3u + 2u] = color.b;
      nonBlack += color.r != 0 || color.g != 0 || color.b != 0;
    }
    std::fwrite(row.data(), 1, row.size(), f);
  }
  std::fclose(f);
  ps1::metrics::count("display_dump.written");
  ps1::metrics::setState("display_dump.nonblack_samples",
                         static_cast<int64_t>(nonBlack));
  fmt::print("[DISPLAY-DUMP] wrote {} ({}x{}), {} non-black samples\n", path,
             width, height, nonBlack);
  return true;
}

// Serialize the immutable native 1x RGB555 display aperture. This is the
// lightweight visual-timing oracle: unlike dumpDisplayPpm(), it neither needs
// the opt-in scalar sidecar nor depends on a Vulkan presentation readback.
static bool dumpNativeDisplayPpm(const ps1::gpu::GPU &gpu, const char *path) {
  std::vector<ps1::gpu::Color16> pixels(
      static_cast<std::size_t>(ps1::gpu::GPU::VRAM_WIDTH) *
      ps1::gpu::GPU::VRAM_HEIGHT);
  ps1::gpu::GPU::DisplayState state{};
  if (gpu.copyDisplayVRAM(pixels.data(), pixels.size(), &state) !=
      pixels.size()) {
    fmt::print(stderr, "[NATIVE-DISPLAY-DUMP] snapshot unavailable\n");
    return false;
  }
  const ps1::gpu::DisplayAperture aperture = ps1::gpu::deriveDisplayAperture(
      state, ps1::gpu::DisplayAreaPolicy::Programmed);

  std::FILE *f = std::fopen(path, "wb");
  if (!f) {
    fmt::print(stderr, "[NATIVE-DISPLAY-DUMP] open failed: {}\n", path);
    return false;
  }
  std::fprintf(f, "P6\n%u %u\n255\n", aperture.width, aperture.height);
  std::vector<uint8_t> row(static_cast<std::size_t>(aperture.width) * 3u);
  for (uint32_t y = 0; y < aperture.height; ++y) {
    for (uint32_t x = 0; x < aperture.width; ++x) {
      const uint16_t pixel =
          aperture.enabled ? pixels[static_cast<std::size_t>(aperture.y + y) *
                                        ps1::gpu::GPU::VRAM_WIDTH +
                                    aperture.x + x]
                                 .raw
                           : 0;
      row[x * 3u + 0u] = static_cast<uint8_t>((pixel & 0x1fu) << 3u);
      row[x * 3u + 1u] = static_cast<uint8_t>(((pixel >> 5u) & 0x1fu) << 3u);
      row[x * 3u + 2u] = static_cast<uint8_t>(((pixel >> 10u) & 0x1fu) << 3u);
    }
    std::fwrite(row.data(), 1, row.size(), f);
  }
  std::fclose(f);
  ps1::metrics::count("native_display_dump.written");
  return true;
}

struct DiagnosticNativeDisplayDumpRange {
  std::filesystem::path directory;
  uint64_t firstVblank = 0;
  uint64_t lastVblank = 0;
  uint64_t step = 1;
  uint64_t lastDumpedVblank = UINT64_MAX;
  bool active = false;

  bool selects(uint64_t vblank) const noexcept {
    return active && vblank >= firstVblank && vblank <= lastVblank &&
           (vblank - firstVblank) % step == 0 && vblank != lastDumpedVblank;
  }
};

static bool parseDiagnosticUnsigned(const char *text, uint64_t &value) {
  if (text == nullptr || *text == '\0' || *text == '-')
    return false;
  char *end = nullptr;
  errno = 0;
  const unsigned long long parsed = std::strtoull(text, &end, 10);
  if (errno != 0 || end == text || *end != '\0')
    return false;
  value = static_cast<uint64_t>(parsed);
  return true;
}

static DiagnosticNativeDisplayDumpRange
configureDiagnosticNativeDisplayDumpRange() {
  DiagnosticNativeDisplayDumpRange range{};
  const char *directory = std::getenv("PS1_NATIVE_DISPLAY_DUMP_DIRECTORY");
  if (directory == nullptr || *directory == '\0')
    return range;

  const char *from = std::getenv("PS1_NATIVE_DISPLAY_DUMP_FROM");
  const char *to = std::getenv("PS1_NATIVE_DISPLAY_DUMP_TO");
  const char *step = std::getenv("PS1_NATIVE_DISPLAY_DUMP_STEP");
  if (!parseDiagnosticUnsigned(from, range.firstVblank) ||
      !parseDiagnosticUnsigned(to, range.lastVblank) ||
      (step != nullptr && !parseDiagnosticUnsigned(step, range.step)) ||
      range.step == 0 || range.lastVblank < range.firstVblank) {
    fmt::print(stderr,
               "[NATIVE-DISPLAY-DUMP] range rejected: DIRECTORY requires valid "
               "FROM/TO and STEP > 0\n");
    return range;
  }

  range.directory = directory;
  std::error_code error;
  std::filesystem::create_directories(range.directory, error);
  if (error) {
    fmt::print(stderr,
               "[NATIVE-DISPLAY-DUMP] cannot create range directory '{}': "
               "{}\n",
               range.directory.string(), error.message());
    return range;
  }
  range.active = true;
  fmt::print("[NATIVE-DISPLAY-DUMP] range {}..{} step {} -> {}\n",
             range.firstVblank, range.lastVblank, range.step,
             range.directory.string());
  return range;
}

// Serialize the complete 512 KiB SPU RAM image. This is intentionally raw:
// audio bring-up tools can inspect ADPCM blocks at their hardware addresses
// without a container adding offsets or changing byte order.
static bool dumpSpuRam(const ps1::spu::SPU &spu, const char *path) {
  std::FILE *f = std::fopen(path, "wb");
  if (!f) {
    fmt::print(stderr, "[SPU-DUMP] open failed: {}\n", path);
    return false;
  }
  const uint8_t *ram = spu.soundRamPtr();
  const size_t size = ps1::spu::SOUND_RAM_SIZE;
  const size_t written = std::fwrite(ram, 1, size, f);
  std::fclose(f);

  uint64_t nonZero = 0;
  for (size_t i = 0; i < size; ++i) {
    if (ram[i] != 0)
      ++nonZero;
  }
  ps1::metrics::count("spu_dump.written");
  ps1::metrics::setState("spu_dump.nonzero_bytes",
                         static_cast<int64_t>(nonZero));
  fmt::print("[SPU-DUMP] wrote {} ({} bytes, {} non-zero)\n", path, written,
             nonZero);
  return written == size;
}

// Serialize the complete 2 MiB main RAM image for boot-state diagnostics.
// The raw physical layout makes PS1 virtual addresses directly inspectable
// after masking them with 0x1FFFFF.
static bool dumpMainRam(const ps1::Memory &memory, const char *path) {
  std::FILE *f = std::fopen(path, "wb");
  if (!f) {
    fmt::print(stderr, "[RAM-DUMP] open failed: {}\n", path);
    return false;
  }
  const size_t written =
      std::fwrite(memory.ramPtr(), 1, ps1::Memory::RAM_SIZE, f);
  std::fclose(f);
  if (written != ps1::Memory::RAM_SIZE) {
    fmt::print(stderr, "[RAM-DUMP] short write: {} of {} bytes\n", written,
               ps1::Memory::RAM_SIZE);
    return false;
  }
  ps1::metrics::count("ram_dump.written");
  fmt::print("[RAM-DUMP] wrote {} ({} bytes)\n", path, written);
  return true;
}

int main(int argc, char *argv[]) {
  if (argc < 2) {
    std::cerr << "Usage: ps1Runtime <ps1_elf_or_iso> [disc_image] [--config "
                 "game.toml]\n"
              << "       ps1Runtime --config game.toml\n";
    return 1;
  }

  std::signal(SIGTERM, onTerminate);
  std::signal(SIGINT, onTerminate);

  // Parse arguments: support --config flag anywhere
  std::string input_path;
  std::string explicit_disc_path;
  std::string config_path;
  for (int i = 1; i < argc; i++) {
    if (std::string(argv[i]) == "--config" && i + 1 < argc) {
      config_path = argv[++i];
    } else if (input_path.empty()) {
      input_path = argv[i];
    } else if (explicit_disc_path.empty()) {
      explicit_disc_path = argv[i];
    }
  }

  // If only a TOML config is provided, read paths from it
  if (input_path.empty() && !config_path.empty()) {
    try {
      auto cfg = toml::parse(config_path);
      if (cfg.contains("disc")) {
        auto &disc = toml::find(cfg, "disc");
        if (disc.contains("exe_path"))
          input_path = toml::find<std::string>(disc, "exe_path");
        if (disc.contains("cue_path"))
          explicit_disc_path = toml::find<std::string>(disc, "cue_path");
      }
    } catch (const std::exception &e) {
      fmt::print(stderr, "Failed to parse config: {}\n", e.what());
      return 1;
    }
  }
  if (input_path.empty()) {
    std::cerr << "No ELF/EXE path provided (via argument or --config)\n";
    return 1;
  }

  // Load the user-facing runtime settings once. Historically main_host parsed
  // the game TOML for paths but silently ignored [video] and [audio], leaving
  // a hard-coded 800x600 window and 1024-sample audio buffer.
  ps1::Config runtimeConfig;
  if (!config_path.empty()) {
    ps1::ConfigReader settings;
    if (settings.load(config_path))
      runtimeConfig = settings.config();
  }
  if (runtimeConfig.video.backend != "vulkan") {
    fmt::print(stderr,
               "Unsupported video backend '{}': this runtime requires "
               "backend = \"vulkan\"\n",
               runtimeConfig.video.backend);
    return 1;
  }
  ps1::games::crash3::ProfileOptions crash3Profile;
  const bool mgsProfile = runtimeConfig.game.profile == ps1::games::mgs::PROFILE_NAME;
  ps1::games::mgs::configure(mgsProfile, runtimeConfig.game.widescreen16x9);
  if (!runtimeConfig.game.profile.empty() && !mgsProfile) {
    if (runtimeConfig.game.profile != ps1::games::crash3::PROFILE_NAME) {
      fmt::print(stderr,
                 "Unknown game.profile '{}'; supported game-specific profile: "
                 "{}\n",
                 runtimeConfig.game.profile, ps1::games::crash3::PROFILE_NAME);
      return 1;
    }
    crash3Profile.enabled = true;
    crash3Profile.widescreen16x9 = runtimeConfig.game.widescreen16x9;
    crash3Profile.presentationDepthCorrections =
        runtimeConfig.game.presentationDepthCorrections;
    crash3Profile.sceneryCullGuardPixels =
        runtimeConfig.game.sceneryCullGuardPixels;
  }
  ps1::games::crash3::configure(crash3Profile);
  if (crash3Profile.enabled) {
    fmt::print("[GameProfile] {}: widescreen {}, presentation depth {}, "
               "scenery guard {} px\n",
               ps1::games::crash3::PROFILE_NAME,
               crash3Profile.widescreen16x9 ? "16:9" : "4:3",
               crash3Profile.presentationDepthCorrections ? "on" : "off",
               ps1::games::crash3::sceneryCullGuardPixels());
  }
  if (mgsProfile) fmt::print("[GameProfile] MGS USA v1.0: {}, native host execution; reference donor CPU 165%\n", ps1::games::mgs::widescreen16x9() ? "16:9" : "4:3");
  const auto displayAreaPolicy =
      ps1::gpu::displayAreaPolicyFromName(runtimeConfig.video.displayArea);
  if (!displayAreaPolicy.has_value()) {
    fmt::print(stderr,
               "Invalid video.display_area '{}': expected programmed, "
               "nominal or donor_canvas\n",
               runtimeConfig.video.displayArea);
    return 1;
  }
  const auto displaySignalProfile = ps1::gpu::displaySignalProfileFromName(
      runtimeConfig.video.displaySignalProfile);
  if (!displaySignalProfile.has_value()) {
    fmt::print(stderr,
               "Invalid video.display_signal_profile '{}': expected "
               "swanstation_no_crop or beetle_uncropped\n",
               runtimeConfig.video.displaySignalProfile);
    return 1;
  }

  // The disc region owns the guest clock. SDL swap cadence is merely how
  // often we present the latest completed PS1 frame and must never select the
  // emulated timing standard.
  bool palTiming = false;
  if (!config_path.empty()) {
    try {
      auto cfg = toml::parse(config_path);
      if (cfg.contains("timing")) {
        const auto &timing = toml::find(cfg, "timing");
        if (timing.contains("video_standard")) {
          std::string standard =
              toml::find<std::string>(timing, "video_standard");
          std::transform(standard.begin(), standard.end(), standard.begin(),
                         [](unsigned char c) { return std::tolower(c); });
          palTiming = standard == "pal";
        }
      }
    } catch (const std::exception &e) {
      fmt::print(stderr, "[WARN] Failed to read timing config: {}\n", e.what());
    }
  }
  const uint32_t guestRefreshHz = palTiming ? 50u : 60u;
  const uint32_t guestScanlines = palTiming ? 314u : 263u;
  ps1::psyq::setVideoMode(palTiming ? 1 : 0);
  fmt::print("[Timing] {} master clock: {} Hz, {} scanlines\n",
             palTiming ? "PAL" : "NTSC", guestRefreshHz, guestScanlines);
  ps1::metrics::setState("timing.refresh_hz", guestRefreshHz);
  ps1::metrics::setState("timing.scanlines", guestScanlines);

  // Optional fallback for heap-loaded native code. Crash 2/3 GOOL entries
  // embed short R3000A blocks whose final RAM address is chosen at runtime,
  // so static dispatch cannot name them ahead of time. The configured range
  // and native-return signature keep this from hiding ordinary recompilation
  // misses or treating arbitrary game data as code.
  if (!config_path.empty()) {
    try {
      auto cfg = toml::parse(config_path);
      if (cfg.contains("dynamic_mips")) {
        auto &dyn = toml::find(cfg, "dynamic_mips");
        auto readAddress = [&](const char *key, uint32_t fallback) {
          if (!dyn.contains(key))
            return fallback;
          auto value = toml::find(dyn, key);
          if (value.is_string())
            return static_cast<uint32_t>(
                std::strtoul(value.as_string().c_str(), nullptr, 0));
          if (value.is_integer())
            return static_cast<uint32_t>(value.as_integer());
          return fallback;
        };
        const bool enabled =
            dyn.contains("enabled") ? toml::find<bool>(dyn, "enabled") : false;
        const uint32_t minAddress = readAddress("min_address", 0x80000000u);
        const uint32_t maxAddress = readAddress("max_address", 0x80200000u);
        ps1::mips::configureDynamicInterpreter(enabled, minAddress, maxAddress);
        if (enabled) {
          fmt::print("[DYN-MIPS] enabled for 0x{:08X}..0x{:08X}\n", minAddress,
                     maxAddress);
        }
      }
    } catch (const std::exception &e) {
      fmt::print(stderr, "[WARN] Failed to read dynamic_mips config: {}\n",
                 e.what());
    }
  }
  fmt::print("ps1Runtime -- PS1 Hardware Simulation (Full Integration)\n");

  // Initialize all hardware subsystems

  // Core
  ps1::Memory memory;
  ps1::gpu::GPU gpu;
  // The authoritative PS1 renderer remains native 1x. Above-native PGXP,
  // true-color and depth resources belong exclusively to Vulkan; keeping the
  // former CPU EnhancedSurface active here both duplicated work and allowed a
  // partially covered companion frame to hide complete native geometry.
  gpu.setProjectiveNearClip(runtimeConfig.video.pgxpNearClip);
  ps1::gpu::configureVulkanNativeOracle(
      gpu, *displayAreaPolicy != ps1::gpu::DisplayAreaPolicy::Nominal);
  const char *scalarOracleMode = std::getenv("PS1_VULKAN_SCALAR_ORACLE");
  const bool scalarOracleEnabled = scalarOracleMode != nullptr &&
                                   scalarOracleMode[0] != '\0' &&
                                   std::strcmp(scalarOracleMode, "0") != 0 &&
                                   std::strcmp(scalarOracleMode, "off") != 0;
  if (scalarOracleEnabled) {
    ps1::gpu::TrueDepthMode scalarDepthMode = ps1::gpu::TrueDepthMode::Hybrid;
    if (std::strcmp(scalarOracleMode, "hybrid") == 0 ||
        std::strcmp(scalarOracleMode, "1") == 0) {
      scalarDepthMode = ps1::gpu::TrueDepthMode::Hybrid;
    } else if (std::strcmp(scalarOracleMode, "strict") == 0) {
      scalarDepthMode = ps1::gpu::TrueDepthMode::Strict;
    } else if (std::strcmp(scalarOracleMode, "painter") == 0) {
      scalarDepthMode = ps1::gpu::TrueDepthMode::Off;
    } else {
      fmt::print(stderr, "[Video] PS1_VULKAN_SCALAR_ORACLE must be 1, hybrid, "
                         "strict, painter, off or 0\n");
      return 1;
    }
    // Diagnostic only: retain the authoritative native raster at 1x while a
    // second 1x sidecar executes the same PGXP/color/depth policy as replay.
    // Vulkan remains the sole presenter and keeps its independently requested
    // 4x policy.  Normal runs allocate neither this surface nor its CPU work.
    gpu.configureEnhancedPresentation(
        1, true, *displayAreaPolicy != ps1::gpu::DisplayAreaPolicy::Nominal);
    gpu.setTrueDepthMode(scalarDepthMode);
    gpu.setEnhancedRaster(true);
    fmt::print("[Video] opt-in scalar visibility oracle: 1x, depth {}\n",
               scalarDepthMode == ps1::gpu::TrueDepthMode::Hybrid ? "hybrid"
               : scalarDepthMode == ps1::gpu::TrueDepthMode::Strict
                   ? "strict"
                   : "painter");
  } else if (!ps1::gpu::isVulkanNativeOraclePolicyActive(gpu)) {
    fmt::print(stderr, "[Video] invariant failure: software raster must remain "
                       "native 1x under Vulkan\n");
    return 1;
  }
  fmt::print(
      "[Video] Vulkan M0 native-complete: software raster 1x, Vulkan "
      "resolve {}x; M1 request: PGXP {}, near plane {}, true depth {}, "
      "true color {}\n",
      runtimeConfig.video.internalResScale,
      runtimeConfig.video.pgxp ? "on" : "off",
      runtimeConfig.video.pgxpNearClip ? "geometric clip" : "GTE saturation",
      runtimeConfig.video.trueDepth ? runtimeConfig.video.trueDepthMode : "off",
      runtimeConfig.video.trueColor ? "on" : "off");
  ps1::spu::SPU spu;
  ps1::DMA dma;
  ps1::InterruptController irqCtrl;
  ps1::Timers timers;
  ps1::input::InputController input;
  input.setPadType(0, runtimeConfig.input.enableAnalog
                          ? ps1::input::PadType::Analog
                          : ps1::input::PadType::Digital);
  const std::filesystem::path memoryCardDirectory = runtimeConfig.paths.memcardDir.empty()
      ? std::filesystem::path("data/memory_cards") : std::filesystem::path(runtimeConfig.paths.memcardDir);
  std::filesystem::create_directories(memoryCardDirectory);
  for (unsigned slot = 0; slot < 2; ++slot) {
    const auto path = memoryCardDirectory / fmt::format("card{}.mcd", slot + 1);
    if (!input.getMemoryCard(slot).attachFile(path.string())) {
      fmt::print(stderr, "[MemoryCard] Cannot load/create {}; existing image preserved\n", path.string());
      return 1;
    }
    fmt::print("[MemoryCard] Slot {}: {}\n", slot + 1, path.string());
  }
  ps1::input::InputScript inputScript;
  bool inputScriptEnabled = false;
  if (const char *path = std::getenv("PS1_INPUT_SCRIPT");
      path != nullptr && *path != '\0') {
    std::string error;
    if (!inputScript.loadFile(path, &error)) {
      fmt::print(stderr, "[InputScript] {}: {}\n", path, error);
      return 1;
    }
    inputScriptEnabled = true;
    fmt::print("[InputScript] loaded {} interval(s) from {}\n",
               inputScript.intervalCount(), path);
  }
  ps1::SaveStateCoordinator stateCoordinator;
  ps1::mdec::MDEC mdec;
  ps1::cdrom::CdromController cdromCtrl;
  ps1::cdrom::VirtualFs fs;

  // Bind emuptr<T> to this Memory instance so hand-written HLE bodies
  // (psyq_hle.cpp etc.) resolve PS1 addresses through the live RAM buffer.
  ps1::emuptr_set_ram(memory.ramPtr());

  // Wire Memory I/O routing
  memory.setGPU(&gpu);
  memory.setSPU(&spu);
  memory.setDMA(&dma);
  memory.setCDROM(&cdromCtrl);
  memory.setInput(&input);
  memory.setMDEC(&mdec);
  memory.setTimers(&timers);
  memory.setInterruptController(&irqCtrl);

  // Wire DMA to devices
  dma.setMemory(&memory);
  dma.setGPU(&gpu);
  dma.setSPU(&spu);
  dma.setCDROM(&cdromCtrl);
  dma.setMDEC(&mdec);

  // Wire CDROM to VirtualFS
  cdromCtrl.attachVirtualFs(&fs);

  // Wire XA-ADPCM from CDROM -> SPU
  cdromCtrl.setXaCallback([&spu](const int16_t *samples, uint32_t count) {
    spu.pushXaSamples(samples, count);
  });

  // CPU Context
  recomp_context ctx;
  ctx.reset();
  ctx.mem = &memory;
  // Initialize Stack Pointer ($sp / r29) to top of 2MB Main RAM (KSEG0)
  ctx.r[29] = 0x801FFFF0;

  // BIOS
  ps1::bios::Bios bios(ctx, fs, memory);
  ctx.bios = &bios;
  bios.setGPU(&gpu);
  bios.setInputController(&input);
  bios.setCdromController(&cdromCtrl);
  bios.setDma(&dma);
  if (mgsProfile) {
    spu.enableGuestClock();
    bios.setSpu(&spu);
  }

  // Enable display (GP1 0x03, val=0): mirrors what the real BIOS does during
  // boot. reset() leaves bit 23 = 1 (display off) per hardware spec.
  gpu.writeGP1(0x03000000);

  // PsyQ HLE layer wiring
  // Phase 2 (2.1 .. 2.4) moved every per-game BSS address into the
  // process-wide `psyq_state()` singleton.  All HleConfig now carries are
  // the GP0/GP1 writers and a callback drain hook -- no addresses.
  {
    ps1::psyq::HleConfig hleCfg;
    hleCfg.drainCallbacks = [&bios]() { bios.drainPendingCallbacks(); };
    hleCfg.writeGP0 = [&gpu](uint32_t w) {
      gpu.writeGP0(w, UINT32_MAX, nullptr,
                   ps1::PGXPSubmissionPath::HleGenerated);
    };
    hleCfg.writeGP0Tracked =
        [&gpu](uint32_t w, uint32_t source, const ps1::PGXPValue *precision,
               uint32_t listStart, uint32_t nodeAddress,
               uint32_t traversalOrdinal, uint32_t orderingTableAnchorAddress,
               bool orderingTableAnchorExact) {
          gpu.writeGP0BatchWord(
              w, source, precision, ps1::PGXPSubmissionPath::HleOrderingTable,
              {listStart, nodeAddress, traversalOrdinal,
               orderingTableAnchorAddress, orderingTableAnchorExact, true});
        };
    hleCfg.beginGP0Batch = [&gpu]() { gpu.beginCommandBatch(); };
    hleCfg.endGP0Batch = [&gpu]() { gpu.endCommandBatch(); };
    hleCfg.activeGP0SubmissionId = [&gpu]() {
      return gpu.activeSubmissionId();
    };
    hleCfg.writeGP1 = [&gpu](uint32_t w) { gpu.writeGP1(w); };
    hleCfg.deliverVBlankEvent = [&bios]() {
      // VSync runs on the game thread. Queue the emulated IRQ-chain work and
      // complete it before returning to guest code, exactly as the real
      // blocking VSync boundary does. Leaving the swap callback queued until
      // the next wait exposes a one-edge-old frame counter to the game and
      // makes titles alternate between one and two waits per simulation step.
      bios.deliverVBlankBoundary();
    };
    hleCfg.stateCheckpoint = [&stateCoordinator, &bios](recomp_context *checkpointCtx,
                                                 uint32_t resumePc) {
      if (!bios.hasNativeThreadContinuations())
        stateCoordinator.checkpoint(*checkpointCtx, resumePc);
    };
    bios.setStateCheckpoint([&](uint32_t pc) { stateCoordinator.checkpoint(ctx, pc); });
    ps1::psyq::configure(hleCfg);
    psyq_registry_init_defaults();
    psyq_register_rayman_boot();
  }

  // Wire controller interrupts into the BIOS queue. Controller state is now
  // game-thread-owned: the host loop only accrues clock credit, and polling
  // yields consume it before any sector/VFS/buffer/IRQ transition occurs.
  // The queue remains useful for a uniform, re-entrancy-safe IRQ surface.
  cdromCtrl.setInterruptCallback(
      [&bios](uint8_t intType) { bios.queueCdromEvent(intType); });

  // A presentation-free diagnostic run still executes the real recompiled
  // game, native 1x GPU oracle, VBlank scheduler and save-state machinery. It
  // exists for surgical CPU/GTE/stream traces and never substitutes a software
  // image for the production Vulkan renderer. In particular it lets geometry
  // provenance be investigated when a window system or Vulkan device is not
  // available, and removes swapchain pacing from short checkpoint probes.
  const bool diagnosticHeadless = [] {
    const char *value = std::getenv("PS1_DIAGNOSTIC_HEADLESS");
    return value != nullptr && *value != '\0' && *value != '0' &&
           std::strcmp(value, "off") != 0;
  }();

  // Initialize SDL2. The headless path has no video dependency; controller
  // events and dummy/real audio retain the same subsystem contracts as an
  // interactive run.
  const uint32_t sdlSubsystems =
      SDL_INIT_AUDIO | SDL_INIT_GAMECONTROLLER |
      (diagnosticHeadless ? 0u : static_cast<uint32_t>(SDL_INIT_VIDEO));
  if (SDL_Init(sdlSubsystems) < 0) {
    fmt::print(stderr, "SDL_Init failed: {}\n", SDL_GetError());
    return 1;
  }
  const auto keyboardMap = makeKeyboardMap(runtimeConfig.input);
  const bool ignoreDiagnosticInput = [] {
    const char *value = std::getenv("PS1_DIAGNOSTIC_IGNORE_INPUT");
    return value != nullptr && *value != '\0' && *value != '0';
  }();
  if (ignoreDiagnosticInput)
    fmt::print("[Input] diagnostic keyboard/controller input disabled\n");

  // Initialize the sole supported video backend. OpenGL and CPU 4x
  // presentation are intentionally not fallback paths.
  ps1::gpu::RendererOptions rendererOptions;
  rendererOptions.displayAreaPolicy = *displayAreaPolicy;
  rendererOptions.displaySignalProfile = *displaySignalProfile;
  rendererOptions.preserveAspect = runtimeConfig.video.preserveAspect;
  rendererOptions.presentationAspectWidth =
      (ps1::games::crash3::widescreen16x9() || ps1::games::mgs::widescreen16x9()) ? 16 : 4;
  rendererOptions.presentationAspectHeight =
      (ps1::games::crash3::widescreen16x9() || ps1::games::mgs::widescreen16x9()) ? 9 : 3;
  rendererOptions.internalScale = runtimeConfig.video.internalResScale;
  if (const char *overrideScale = std::getenv("PS1_INTERNAL_RES_SCALE")) {
    char *end = nullptr;
    errno = 0;
    const long parsed = std::strtol(overrideScale, &end, 10);
    if (errno != 0 || end == overrideScale || *end != '\0' || parsed < 1 ||
        parsed > 8) {
      fmt::print(stderr,
                 "[Vulkan] invalid PS1_INTERNAL_RES_SCALE '{}': expected "
                 "1..8\n",
                 overrideScale);
      return 1;
    }
    rendererOptions.internalScale = static_cast<int>(parsed);
    fmt::print("[Vulkan] diagnostic internal scale: {}x\n", parsed);
  }
  rendererOptions.pgxp = runtimeConfig.video.pgxp;
  rendererOptions.pgxpNearClip = runtimeConfig.video.pgxpNearClip;
  rendererOptions.trueDepth = runtimeConfig.video.trueDepth;
  rendererOptions.trueDepthMode = runtimeConfig.video.trueDepthMode;
  rendererOptions.wipDepthManifest = runtimeConfig.video.wipDepthManifest;
  rendererOptions.trueColor = runtimeConfig.video.trueColor;
  if (const char *meshMode = std::getenv("PS1_MGS_MESH_REPLAY");
      ps1::games::mgs::active() && meshMode &&
      std::strcmp(meshMode, "1") == 0) {
    // Use the inherited, tested complete replay executor. The authoritative
    // native raster remains 1x; these options affect presentation only.
    rendererOptions.internalScale = 4;
    rendererOptions.pgxp = true;
    rendererOptions.pgxpNearClip = false;
    rendererOptions.trueDepth = true;
    rendererOptions.trueDepthMode = "hybrid";
    rendererOptions.trueColor = true;
    fmt::print("[MGS mesh] original-cache Vulkan projection, 4x ordered "
               "composition\n");
  }
  if (const char *disableReplay = std::getenv("PS1_DISABLE_PRECISION_REPLAY");
      disableReplay != nullptr && *disableReplay != '\0' &&
      *disableReplay != '0') {
    rendererOptions.internalScale = 1;
    rendererOptions.pgxp = false;
    rendererOptions.pgxpNearClip = false;
    rendererOptions.trueDepth = false;
    rendererOptions.trueColor = false;
    ps1::configurePGXPTracking(false);
    fmt::print("[Vulkan] diagnostic precision replay and CPU provenance "
               "tracking disabled\n");
  }
  bool presentationVsync = runtimeConfig.video.vsync;
  if (const char *overrideVsync = std::getenv("PS1_PRESENT_VSYNC")) {
    if (overrideVsync[0] == '0' && overrideVsync[1] == '\0')
      presentationVsync = false;
    else if (overrideVsync[0] == '1' && overrideVsync[1] == '\0')
      presentationVsync = true;
    fmt::print("[Vulkan] diagnostic presentation VSync: {}\n",
               presentationVsync ? "on" : "off");
  }
  ps1::gpu::RendererVulkan renderer(gpu, rendererOptions);
  const char *presentationTitle = std::getenv("PS1_WINDOW_TITLE");
  if (presentationTitle == nullptr || presentationTitle[0] == '\0')
    presentationTitle = "ps1Recomp";
  if (!diagnosticHeadless &&
      !renderer.init(presentationTitle, runtimeConfig.video.windowWidth,
                     runtimeConfig.video.windowHeight, presentationVsync,
                     runtimeConfig.video.fullscreen)) {
    fmt::print(stderr, "Failed to initialize Vulkan renderer!\n");
    SDL_Quit();
    return 1;
  }
  if (diagnosticHeadless) {
    fmt::print("[Video] diagnostic headless execution: no presenter; native "
               "1x oracle and guest rendering remain active\n");
    ps1::metrics::setState("host.renderer.diagnostic_headless", 1);
  }

  // SDL2 Audio
  g_spu = &spu;
  g_audioVolume = runtimeConfig.audio.volume;
  g_audioMute = runtimeConfig.audio.mute;
  SDL_AudioSpec desired{}, obtained{};
  desired.freq = runtimeConfig.audio.sampleRate;
  desired.format = AUDIO_S16SYS;
  desired.channels = 2;
  desired.samples = static_cast<uint16_t>(runtimeConfig.audio.bufferSize);
  desired.callback = audioCallback;

  SDL_AudioDeviceID audioDevice =
      SDL_OpenAudioDevice(nullptr, 0, &desired, &obtained, 0);
  if (audioDevice > 0) {
    SDL_PauseAudioDevice(audioDevice, 0); // Start playback
    fmt::print("[Audio] SDL2 audio: {}Hz, {} ch, {} samples/buffer\n",
               obtained.freq, obtained.channels, obtained.samples);
  } else {
    fmt::print(stderr, "[Audio] Warning: could not open audio: {}\n",
               SDL_GetError());
  }

  // SDL2 GameController
  SDL_GameController *gamepad = nullptr;
  std::array<Sint16, SDL_CONTROLLER_AXIS_MAX> gamepadAxes{};
  for (int i = 0; i < SDL_NumJoysticks(); i++) {
    if (SDL_IsGameController(i)) {
      gamepad = SDL_GameControllerOpen(i);
      if (gamepad) {
        fmt::print("[Input] GameController: {}\n",
                   SDL_GameControllerName(gamepad));
        break;
      }
    }
  }

  // Load ELF or ISO

  ps1recomp::ElfParser parser;
  if (!parser.load(input_path)) {
    fmt::print(stderr, "Failed to load ELF: {}\n", parser.getError());
    renderer.destroy();
    SDL_Quit();
    return 1;
  }

  // Auto-load corresponding Disc Image if running a extracted .boot.exe
  if (!explicit_disc_path.empty()) {
    // Disc image was explicitly provided as first argument
    if (fs.loadDisc(explicit_disc_path)) {
      fmt::print("[CDROM] Mounted disc image: {}\n", explicit_disc_path);
    } else {
      fmt::print(stderr, "[CDROM] WARNING: Could not mount disc image: {}\n",
                 explicit_disc_path);
    }
  } else {
    std::string disc_path = input_path;
    if (disc_path.ends_with(".boot.exe")) {
      disc_path =
          disc_path.substr(0, disc_path.length() - 9); // strip ".boot.exe"
      if (fs.loadDisc(disc_path)) {
        fmt::print("[CDROM] Automatically mounted disc image: {}\n", disc_path);
      } else {
        fmt::print(
            stderr,
            "[CDROM] WARNING: Could not mount corresponding disc image: {}\n",
            disc_path);
      }
    } else if (disc_path.ends_with(".bin") || disc_path.ends_with(".cue")) {
      if (fs.loadDisc(disc_path)) {
        fmt::print("[CDROM] Mounted disc image: {}\n", disc_path);
      }
    }
  }

  auto sections = parser.getSections();
  int loaded_sections = 0;
  for (const auto &sec : sections) {
    if ((sec.type == ps1recomp::SectionType::Text ||
         sec.type == ps1recomp::SectionType::Data) &&
        sec.data != nullptr) {
      uint32_t phys = ps1::Memory::toPhysical(sec.vaddr);
      if (phys < ps1::Memory::RAM_SIZE) {
        std::memcpy(memory.ramPtr() + phys, sec.data, sec.size);
        loaded_sections++;
      }
    }
  }
  fmt::print("Loaded {} sections into PS1 memory.\n", loaded_sections);

  // Apply [memory_init] pre-initialization
  // Some games need specific PS1 RAM locations pre-initialized before the
  // game code runs (e.g., PsyQ BSS pointer tables that CdInit would normally
  // set up but can't due to bootstrap timing in the recompiled environment).
  if (!config_path.empty()) {
    try {
      auto cfg = toml::parse(config_path);
      if (cfg.contains("memory_init")) {
        auto &mi = toml::find(cfg, "memory_init");
        if (mi.is_table()) {
          for (const auto &[key, val] : mi.as_table()) {
            uint32_t addr = std::strtoul(key.c_str(), nullptr, 0);
            uint32_t data = 0;
            if (val.is_integer()) {
              data = static_cast<uint32_t>(val.as_integer());
            } else if (val.is_string()) {
              data = std::strtoul(val.as_string().c_str(), nullptr, 0);
            }
            uint32_t phys = ps1::Memory::toPhysical(addr);
            if (phys + 4 <= ps1::Memory::RAM_SIZE) {
              memory.write32(addr, data);
              fmt::print("[memory_init] 0x{:08X} = 0x{:08X}\n", addr, data);
            } else {
              fmt::print(
                  stderr,
                  "[memory_init] WARN: address 0x{:08X} out of RAM range\n",
                  addr);
            }
          }
        }
      }
    } catch (const std::exception &e) {
      fmt::print(stderr, "[WARN] Failed to read memory_init from config: {}\n",
                 e.what());
    }
  }

  // Main Emulation Loop
  // Game code runs in a separate thread (it never returns).
  // Main thread handles SDL events + hardware ticking + rendering.

  uint32_t entryPoint = parser.getEntryPoint();
  fmt::print("Starting emulation... Entry Point: 0x{:08X}\n", entryPoint);

  // DEBUG: verify binary data integrity at known vtable addresses
  {
    uint32_t dbgAddrs[] = {0x800549BC, 0x8005499C, 0x800549A4, 0x800549A8};
    for (auto a : dbgAddrs) {
      uint32_t phys = ps1::Memory::toPhysical(a);
      if (phys + 4 <= ps1::Memory::RAM_SIZE) {
        uint32_t val = memory.read32(a);
        fmt::print("[DBG] 0x{:08X} = 0x{:08X}\n", a, val);
      }
    }
  }
  std::atomic<bool> gameRunning{true};
  // `gameFinished` = "shutdown requested" (set by main or game thread)
  // `gameThreadDone` = "game thread lambda has returned" (set only by game
  // thread). Splitting these avoids the UAF in shutdown: previously the
  // cleanup code set `gameFinished` to request shutdown, then waited
  // `while (!gameFinished)` -- which already returned true the instant after
  // the request -- so the wait exited immediately and the still-running
  // game thread was detach()ed, leaving it racing with `Bios::~Bios()`
  // destructing `cdEventQueue_`.  See ISSUES.md #1.
  std::atomic<bool> gameFinished{false};
  std::atomic<bool> gameThreadDone{false};
  uint64_t frameCount = 0;
  // Set once PS1_VRAM_DUMP_FRAME has been honoured, so the shutdown dump does
  // not overwrite the requested frame -- both write PS1_VRAM_DUMP_PATH, and
  // the shutdown VRAM is exactly the freshly-cleared state we are avoiding.
  bool frameDumpWritten = false;
  bool displayFrameDumpWritten = false;
  DiagnosticNativeDisplayDumpRange nativeDisplayDumpRange =
      configureDiagnosticNativeDisplayDumpRange();
  std::filesystem::path saveStateDirectory =
      runtimeConfig.paths.saveStateDir.empty()
          ? std::filesystem::path("savestates")
          : std::filesystem::path(runtimeConfig.paths.saveStateDir);
  if (const char *diagnosticDirectory =
          std::getenv("PS1_DIAGNOSTIC_SAVESTATE_DIR");
      diagnosticDirectory != nullptr && *diagnosticDirectory != '\0') {
    saveStateDirectory = diagnosticDirectory;
    fmt::print("[SaveState] diagnostic directory: {}\n",
               saveStateDirectory.string());
  }
  std::error_code saveDirectoryError;
  std::filesystem::create_directories(saveStateDirectory, saveDirectoryError);
  if (saveDirectoryError) {
    fmt::print(stderr, "[SaveState] Cannot create '{}': {}\n",
               saveStateDirectory.string(), saveDirectoryError.message());
  }
  unsigned saveStateSlot = 0;
  uint32_t stateWindowId = 0;
  const auto saveStatePath = [&]() {
    return (saveStateDirectory /
            fmt::format("quick_slot_{}.ps1s", saveStateSlot))
        .string();
  };
  if (mgsProfile)
    fmt::print("[Input] keyboard + SDL GameController enabled; F5 save, F9 load, F6/F7 slot\n");
  else
    fmt::print("[Input] keyboard + SDL GameController enabled; F5 save, F9 "
               "load, F6/F7 slot, F8 depth\n");

  // Initialize dispatch table before starting the game
  recomp_init_dispatch_table();
  fmt::print("[Dispatch] Table initialized.\n");

  // Optional guest-RAM write trace for bring-up diagnostics.  The Memory
  // watchpoint compares physical addresses, so KUSEG/KSEG0/KSEG1 spellings
  // all match.  Capturing the live CPU context also exposes the guest return
  // address, which identifies the recompiled function performing the write.
  // Keep this opt-in: tracing a hot game variable can otherwise produce a
  // prohibitive amount of output.
  std::atomic<uint32_t> ramWatchHits{0};
  if (const char *watchAddr = std::getenv("PS1_RAM_WATCH_ADDR")) {
    const uint32_t address = std::strtoul(watchAddr, nullptr, 0);
    uint32_t limit = 64;
    if (const char *watchLimit = std::getenv("PS1_RAM_WATCH_LIMIT"))
      limit = std::strtoul(watchLimit, nullptr, 0);
    memory.setWriteWatchpoint(address, [&, address, limit](uint32_t value) {
      const uint32_t hit = ramWatchHits.fetch_add(1, std::memory_order_relaxed);
      if (hit < limit) {
        fmt::print(stderr,
                   "[RAM-WATCH] #{} addr=0x{:08X} value=0x{:08X} "
                   "guest_ra=0x{:08X}\n",
                   hit + 1, address, value, ctx.r[31]);
      }
    });
    fmt::print("[RAM-WATCH] tracing 0x{:08X} (limit {})\n", address, limit);
  }

  // BSS mirror addresses (per-game polling slots)
  // Phase 2.2 retired the per-game VBlank counter BSS slot in favor of
  // `psyq_state().vsyncCounter` (atomic).  PsyQ HLE reads the singleton.
  // BUT: recompiled native MIPS code can poll the legacy BSS address
  // directly (`MEM_READ32(0x801CF2CC)` in Rayman) -- without a write-
  // through, those polls observe 0 forever and the game thread spins.
  //
  // `[bss_mirrors]` (TOML, optional) declares which BSS slots the VBlank
  // ticker should mirror.  When set, the thread does an atomic
  // `vsyncCounter` bump AND a `mem.write32(addr, counter)` so legacy
  // polling continues to work with the current architecture.
  uint32_t vblankCounterMirror = 0;
  uint32_t cdSyncMirror = 0;
  uint32_t cdReadyMirror = 0;
  if (!config_path.empty()) {
    try {
      auto cfg = toml::parse(config_path);
      if (cfg.contains("bss_mirrors")) {
        auto &mirrors = toml::find(cfg, "bss_mirrors");
        if (mirrors.is_table()) {
          auto readAddr = [&](const char *key) -> uint32_t {
            if (!mirrors.contains(key))
              return 0;
            auto v = toml::find(mirrors, key);
            if (v.is_string())
              return std::strtoul(v.as_string().c_str(), nullptr, 0);
            if (v.is_integer())
              return static_cast<uint32_t>(v.as_integer());
            return 0;
          };
          vblankCounterMirror = readAddr("vblank_counter");
          cdSyncMirror = readAddr("cd_sync_byte");
          cdReadyMirror = readAddr("cd_ready_byte");
          if (vblankCounterMirror != 0)
            fmt::print("[bss_mirrors] vblank_counter = 0x{:08X}\n",
                       vblankCounterMirror);
          if (cdSyncMirror != 0)
            fmt::print("[bss_mirrors] cd_sync_byte   = 0x{:08X}\n",
                       cdSyncMirror);
          if (cdReadyMirror != 0)
            fmt::print("[bss_mirrors] cd_ready_byte  = 0x{:08X}\n",
                       cdReadyMirror);
        }
      }
    } catch (const std::exception &) {
      // Optional section -- silent fallback.
    }
  }
  bios.setBssMirrors(cdSyncMirror, cdReadyMirror);

  // The scheduler owns wall-clock pacing, not guest time. The main thread
  // turns a pulse into one ordered hardware/VBlank advance. Missed host
  // deadlines are coalesced below: replaying them would expose renderer or
  // diagnostic cost as a burst of guest callbacks.
  auto vblankPeriod = std::chrono::nanoseconds(1000000000ull / guestRefreshHz);
  if (const char *periodEnv = std::getenv("PS1_VBLANK_PERIOD_US")) {
    const unsigned long requested = std::strtoul(periodEnv, nullptr, 0);
    if (requested > 0 && requested <= UINT32_MAX) {
      vblankPeriod = std::chrono::microseconds(requested);
      fmt::print("[VBlank] diagnostic period: {} us\n", requested);
    }
  }
  std::atomic<uint64_t> scheduledVblanks{0};
  std::thread vblankThread([&]() {
    using namespace std::chrono;
    auto next = steady_clock::now() + vblankPeriod;
    while (!gameFinished.load(std::memory_order_acquire)) {
      std::this_thread::sleep_until(next);
      const auto now = steady_clock::now();
      next += vblankPeriod;
      if (next <= now)
        next = now + vblankPeriod;
      scheduledVblanks.fetch_add(1, std::memory_order_release);
    }
  });

  // Launch game thread
  std::thread gameThread([&]() {
    // Identify ourselves so Bios::queueCdromEvent can inline-drain when
    // the IRQ callback fires synchronously from MIPS-driven port writes
    // on this thread.
    bios.setGameThreadId(std::this_thread::get_id());
    ctx.pc = entryPoint;
    while (!gameFinished.load(std::memory_order_acquire)) {
      try {
        if (ctx.nativeResumePc != 0)
          recomp_resume_dispatch(memory.ramPtr(), &ctx, ctx.nativeResumePc);
        else
          recomp_dispatch(memory.ramPtr(), &ctx, ctx.pc);
        break;
      } catch (const ps1::SaveStateTimelineReload &) {
        bios.restartNativeThreads();
        fmt::print("[SaveState] guest dispatcher resumed at 0x{:08X}\n",
                   ctx.pc);
        ctx.nativeResumePc = ctx.pc;
      } catch (const ps1::CpuException &e) {
        fmt::print("[Game] CPU Exception {} at PC=0x{:08X}\n",
                   static_cast<uint32_t>(e.cause), ctx.pc);
        break;
      } catch (const std::exception &e) {
        fmt::print("[Game] Exception: {}\n", e.what());
        break;
      } catch (...) {
        fmt::print("[Game] Unknown exception\n");
        break;
      }
    }
    gameFinished.store(true, std::memory_order_release);
    gameThreadDone.store(true, std::memory_order_release);
  });

  const uint32_t guestCyclesPerVblank = CPU_CLOCK / guestRefreshHz;
  const uint32_t baseCyclesPerScanline = guestCyclesPerVblank / guestScanlines;
  const uint32_t extraScanlineCycles = guestCyclesPerVblank % guestScanlines;
  uint64_t metricsFlushVblanks = 0;
  if (const char *flush = std::getenv("PS1_METRICS_FLUSH_VBLANKS"))
    metricsFlushVblanks = std::strtoull(flush, nullptr, 0);
  uint64_t exitVblank = 0;
  if (const char *stop = std::getenv("PS1_EXIT_VBLANK")) {
    exitVblank = std::strtoull(stop, nullptr, 0);
    if (exitVblank != 0)
      fmt::print("[VBlank] diagnostic exit at {}\n", exitVblank);
  }
  uint64_t exitAfterLoadVblanks = 0;
  if (const char *stop = std::getenv("PS1_EXIT_AFTER_LOAD_VBLANKS")) {
    exitAfterLoadVblanks = std::strtoull(stop, nullptr, 0);
    if (exitAfterLoadVblanks != 0) {
      fmt::print("[VBlank] diagnostic exit {} VBlanks after a state load\n",
                 exitAfterLoadVblanks);
    }
  }
  uint64_t exitAfterLoadTarget = 0;
  const auto diagnosticVblank = [](const char *name) {
    const char *value = std::getenv(name);
    return value ? std::strtoull(value, nullptr, 0) : uint64_t{0};
  };
  const uint64_t autoSaveVblank = diagnosticVblank("PS1_AUTOSAVE_VBLANK");
  const uint64_t autoLoadVblank = diagnosticVblank("PS1_AUTOLOAD_VBLANK");
  const uint64_t autoLoadCount = std::max<uint64_t>(1, diagnosticVblank("PS1_AUTOLOAD_COUNT"));
  uint64_t completedAutoLoads = 0;
  bool autoSaveRequested = false;
  bool autoLoadRequested = false;
  bool autoSaveCompleted = false;
  bool autoLoadCompleted = false;
  const bool exitAfterAutoSave = [] {
    const char *value = std::getenv("PS1_EXIT_AFTER_AUTOSAVE");
    return value != nullptr && *value != '\0' && *value != '0';
  }();
  if (autoSaveVblank != 0)
    fmt::print("[SaveState] diagnostic autosave at VBlank {}\n",
               autoSaveVblank);
  if (autoLoadVblank != 0)
    fmt::print("[SaveState] diagnostic autoload at VBlank {}\n",
               autoLoadVblank);
  const bool crash3DemoCheckpointing = [] {
    const char *value = std::getenv("PS1_CRASH3_AUTOSAVE_DEMO_LEVELS");
    return value != nullptr && *value != '\0' && *value != '0';
  }();
  uint64_t crash3DemoIdleVblanks = 100u;
  if (const char *value =
          std::getenv("PS1_CRASH3_DEMO_CHECKPOINT_IDLE_VBLANKS")) {
    uint64_t parsed = 0u;
    if (parseDiagnosticUnsigned(value, parsed) && parsed != 0u)
      crash3DemoIdleVblanks = parsed;
  }
  uint64_t crash3DemoLoadDelayVblanks = 600u;
  if (const char *value =
          std::getenv("PS1_CRASH3_DEMO_CHECKPOINT_DELAY_VBLANKS")) {
    uint64_t parsed = 0u;
    if (parseDiagnosticUnsigned(value, parsed) && parsed != 0u)
      crash3DemoLoadDelayVblanks = parsed;
  }
  const bool exitOnCrash3DemoRepeat = [] {
    const char *value =
        std::getenv("PS1_CRASH3_DEMO_CHECKPOINT_EXIT_ON_REPEAT");
    return value != nullptr && *value != '\0' && *value != '0';
  }();
  uint32_t crash3DemoLastCapture = 0u;
  uint64_t crash3DemoLastCaptureVblank = 0u;
  uint32_t crash3DemoCheckpointIndex = 0u;
  bool crash3DemoCheckpointArmed = true;
  std::unordered_set<uint64_t> crash3DemoCheckpointFingerprints;
  std::unordered_set<uint8_t> crash3DemoCheckpointLevelCodes;
  uint64_t crash3DemoLastLoadGeneration = 0u;
  uint64_t crash3DemoPendingLoadVblank = 0u;
  uint8_t crash3DemoPendingLevelCode = 0u;
  if (crash3DemoCheckpointing) {
    fmt::print("[SaveState] Crash 3 demo checkpoints enabled; re-arm after {} "
               "scenery-idle VBlanks; loader checkpoint delay {} VBlanks\n",
               crash3DemoIdleVblanks, crash3DemoLoadDelayVblanks);
  }
  uint64_t processedVblanks = 0;
  uint64_t peakVblankDebt = 0;
  const uint64_t maxVblanksPerPresent =
      std::clamp<uint64_t>(runtimeConfig.video.maxVblanksPerPresent, 1, 16);
  ps1::metrics::setState("timing.vblank_slice_limit",
                         static_cast<int64_t>(maxVblanksPerPresent));
  fmt::print("[VBlank] pacing slice: at most {} tick(s) per present; excess "
             "host pulses coalesce\n",
             maxVblanksPerPresent);
  const auto hostLoopEpoch = std::chrono::steady_clock::now();
  std::optional<std::chrono::steady_clock::time_point> diagnosticLoadEpoch;
  uint64_t diagnosticRestoredVblank = 0u;
  bool running = true;
  while (running) {
    bool diagnosticExitAfterPresent = false;
    // 1. Poll SDL2 Events
    SDL_Event event;
    while (SDL_PollEvent(&event)) {
      switch (event.type) {
      case SDL_QUIT:
        running = false;
        break;
      case SDL_KEYDOWN:
        if (ignoreDiagnosticInput) {
          break;
        } else if (event.key.keysym.sym == SDLK_ESCAPE) {
          running = false;
        } else if (event.key.keysym.sym == SDLK_F5 && event.key.repeat == 0) {
          stateWindowId = event.key.windowID;
          const std::string path = saveStatePath();
          if (stateCoordinator.request(ps1::SaveStateCoordinator::Action::Save,
                                       path))
            fmt::print("[SaveState] save requested: slot {}\n", saveStateSlot);
        } else if (event.key.keysym.sym == SDLK_F9 && event.key.repeat == 0) {
          stateWindowId = event.key.windowID;
          const std::string path = saveStatePath();
          if (stateCoordinator.request(ps1::SaveStateCoordinator::Action::Load,
                                       path))
            fmt::print("[SaveState] load requested: slot {}\n", saveStateSlot);
        } else if (event.key.keysym.sym == SDLK_F6 && event.key.repeat == 0) {
          saveStateSlot = (saveStateSlot + 9u) % 10u;
          fmt::print("[SaveState] selected slot {}\n", saveStateSlot);
        } else if (event.key.keysym.sym == SDLK_F7 && event.key.repeat == 0) {
          saveStateSlot = (saveStateSlot + 1u) % 10u;
          fmt::print("[SaveState] selected slot {}\n", saveStateSlot);
        } else if (!diagnosticHeadless && event.key.keysym.sym == SDLK_F8 &&
                   event.key.repeat == 0) {
          renderer.toggleDepthVisualization();
        } else {
          mapKeyToButton(event.key.keysym.sym, keyboardMap, input, true);
        }
        break;
      case SDL_KEYUP:
        if (!ignoreDiagnosticInput)
          mapKeyToButton(event.key.keysym.sym, keyboardMap, input, false);
        break;
      case SDL_CONTROLLERBUTTONDOWN:
      case SDL_CONTROLLERBUTTONUP: {
        if (ignoreDiagnosticInput)
          break;
        const uint16_t button = controllerButton(event.cbutton.button);
        if (button != 0) {
          if (event.type == SDL_CONTROLLERBUTTONDOWN)
            input.press(button, 0);
          else
            input.release(button, 0);
        }
        break;
      }
      case SDL_CONTROLLERAXISMOTION: {
        if (ignoreDiagnosticInput)
          break;
        const auto axis = static_cast<SDL_GameControllerAxis>(event.caxis.axis);
        if (axis >= 0 && axis < SDL_CONTROLLER_AXIS_MAX)
          gamepadAxes[axis] = event.caxis.value;
        input.setAnalog(0, analogByte(gamepadAxes[SDL_CONTROLLER_AXIS_LEFTX]),
                        analogByte(gamepadAxes[SDL_CONTROLLER_AXIS_LEFTY]),
                        analogByte(gamepadAxes[SDL_CONTROLLER_AXIS_RIGHTX]),
                        analogByte(gamepadAxes[SDL_CONTROLLER_AXIS_RIGHTY]));
        constexpr Sint16 triggerThreshold = 16000;
        if (axis == SDL_CONTROLLER_AXIS_TRIGGERLEFT) {
          if (event.caxis.value >= triggerThreshold)
            input.press(ps1::input::BTN_L2, 0);
          else
            input.release(ps1::input::BTN_L2, 0);
        } else if (axis == SDL_CONTROLLER_AXIS_TRIGGERRIGHT) {
          if (event.caxis.value >= triggerThreshold)
            input.press(ps1::input::BTN_R2, 0);
          else
            input.release(ps1::input::BTN_R2, 0);
        }
        break;
      }
      }
    }

    const uint64_t inputVblank =
        ps1::psyq::psyq_state().vsyncCounter.load(std::memory_order_acquire);
    if (!autoSaveRequested && autoSaveVblank != 0 &&
        inputVblank >= autoSaveVblank &&
        stateCoordinator.request(ps1::SaveStateCoordinator::Action::Save,
                                 saveStatePath())) {
      autoSaveRequested = true;
      fmt::print("[SaveState] diagnostic save requested at VBlank {}\n",
                 inputVblank);
    }
    if (!autoLoadRequested && autoLoadVblank != 0 &&
        inputVblank >= autoLoadVblank &&
        stateCoordinator.request(ps1::SaveStateCoordinator::Action::Load,
                                 saveStatePath())) {
      autoLoadRequested = true;
      fmt::print("[SaveState] diagnostic load requested at VBlank {}\n",
                 inputVblank);
    }

    stateCoordinator.service(
        [&](const ps1::SaveStateCoordinator::Request &req) {
          if (audioDevice > 0)
            SDL_LockAudioDevice(audioDevice);
          const bool succeeded =
              req.action == ps1::SaveStateCoordinator::Action::Save
                  ? ps1::SaveState::save(req.path, ctx, memory, gpu, spu, dma,
                                         cdromCtrl, timers, irqCtrl, input,
                                         &mdec, &bios)
                  : ps1::SaveState::load(req.path, ctx, memory, gpu, spu, dma,
                                         cdromCtrl, timers, irqCtrl, input,
                                         &mdec, &bios);
          if (audioDevice > 0)
            SDL_UnlockAudioDevice(audioDevice);
          if (stateWindowId) {
            if (auto *window = SDL_GetWindowFromID(stateWindowId)) {
              const auto message = fmt::format("Metal Gear Solid - {}: {}",
                  succeeded ? (req.action == ps1::SaveStateCoordinator::Action::Save
                                   ? "Stato salvato" : "Stato caricato")
                            : "Operazione savestate fallita",
                  std::filesystem::path(req.path).filename().string());
              SDL_SetWindowTitle(window, message.c_str());
            }
          }
          if (succeeded &&
              req.action == ps1::SaveStateCoordinator::Action::Load) {
            ps1::metrics::armGuestTraceAfterLoad();
            const uint64_t restoredVblank =
                ps1::psyq::psyq_state().vsyncCounter.load(
                    std::memory_order_acquire);
            processedVblanks = restoredVblank;
            scheduledVblanks.store(restoredVblank, std::memory_order_release);
            if (exitAfterLoadVblanks != 0) {
              exitAfterLoadTarget =
                  restoredVblank > std::numeric_limits<uint64_t>::max() -
                                       exitAfterLoadVblanks
                      ? std::numeric_limits<uint64_t>::max()
                      : restoredVblank + exitAfterLoadVblanks;
              fmt::print("[VBlank] restored at {}; relative diagnostic exit "
                         "at {}\n",
                         restoredVblank, exitAfterLoadTarget);
            }
            if (!diagnosticHeadless)
              renderer.rebaseGuestTimeline();
            gpu.snapshotDisplayBuffer(restoredVblank);
            autoLoadCompleted = true;
            if (++completedAutoLoads < autoLoadCount) autoLoadRequested = false;
            diagnosticRestoredVblank = restoredVblank;
            diagnosticLoadEpoch = std::chrono::steady_clock::now();
          }
          ps1::metrics::count(
              succeeded ? (req.action == ps1::SaveStateCoordinator::Action::Save
                               ? "host.savestate.saved"
                               : "host.savestate.loaded")
                        : "host.savestate.failed");
          if (succeeded &&
              req.action == ps1::SaveStateCoordinator::Action::Save)
            autoSaveCompleted = true;
          return succeeded;
        });

    // The title screen has no resident scenery construction.  A sufficiently
    // long capture gap therefore arms the next stable intrinsic resource
    // cohort as a new unattended demo episode.  This deliberately observes
    // only host sidecar state: it injects no pad input and writes no guest RAM.
    if (crash3DemoCheckpointing &&
        (autoLoadVblank == 0u || autoLoadCompleted)) {
      const uint64_t checkpointVblank =
          ps1::psyq::psyq_state().vsyncCounter.load(std::memory_order_acquire);
      const ps1::games::crash3::DemoLevelLoadSignal loadSignal =
          ps1::games::crash3::demoLevelLoadSignal();
      if (loadSignal.generation != 0u &&
          loadSignal.generation != crash3DemoLastLoadGeneration) {
        crash3DemoLastLoadGeneration = loadSignal.generation;
        if (loadSignal.title) {
          crash3DemoPendingLevelCode = 0u;
          fmt::print("[SaveState] Crash 3 demo title marker at VBlank {} "
                     "(load {})\n",
                     checkpointVblank, loadSignal.loadOrdinal);
        } else {
          const bool repeated =
              crash3DemoCheckpointLevelCodes.contains(loadSignal.levelCode);
          if (repeated) {
            fmt::print("[SaveState] Crash 3 demo cycle repeated level code "
                       "0x{:02X} at VBlank {}\n",
                       loadSignal.levelCode, checkpointVblank);
            crash3DemoPendingLevelCode = 0u;
            if (exitOnCrash3DemoRepeat)
              running = false;
          } else {
            crash3DemoPendingLevelCode = loadSignal.levelCode;
            crash3DemoPendingLoadVblank = checkpointVblank;
            crash3DemoCheckpointArmed = true;
            fmt::print("[SaveState] Crash 3 demo level code 0x{:02X} armed "
                       "at VBlank {} (load {})\n",
                       loadSignal.levelCode, checkpointVblank,
                       loadSignal.loadOrdinal);
          }
        }
      }
      if (crash3DemoLastCapture != 0u &&
          checkpointVblank >=
              crash3DemoLastCaptureVblank + crash3DemoIdleVblanks) {
        crash3DemoCheckpointArmed = true;
      }
      const ps1::games::crash3::ResidentPresentationCheckpointSignal signal =
          ps1::games::crash3::residentPresentationCheckpointSignal();
      if (signal.captureId != 0u && signal.captureId != crash3DemoLastCapture) {
        crash3DemoLastCapture = signal.captureId;
        crash3DemoLastCaptureVblank = checkpointVblank;
        // Loader markers are the complete per-game episode identity. Keep the
        // older scenery-only path as a fallback for checkpoints restored
        // after the marker or for revisions without that debug format.
        if (crash3DemoLastLoadGeneration == 0u && crash3DemoCheckpointArmed &&
            signal.stable && !stateCoordinator.pending()) {
          const bool inserted = crash3DemoCheckpointFingerprints
                                    .insert(signal.activeCohortFingerprint)
                                    .second;
          if (inserted) {
            const std::string path =
                (saveStateDirectory /
                 fmt::format("demo_level_{:03}_vblank_{}.ps1s",
                             crash3DemoCheckpointIndex, checkpointVblank))
                    .string();
            if (stateCoordinator.request(
                    ps1::SaveStateCoordinator::Action::Save, path)) {
              fmt::print("[SaveState] Crash 3 demo level {} requested at "
                         "VBlank {} (capture {}, cohort 0x{:016X})\n",
                         crash3DemoCheckpointIndex, checkpointVblank,
                         signal.captureId, signal.activeCohortFingerprint);
              ++crash3DemoCheckpointIndex;
              crash3DemoCheckpointArmed = false;
            }
          } else {
            fmt::print("[SaveState] Crash 3 demo cycle repeated cohort "
                       "0x{:016X} at VBlank {}\n",
                       signal.activeCohortFingerprint, checkpointVblank);
            crash3DemoCheckpointArmed = false;
            if (exitOnCrash3DemoRepeat)
              running = false;
          }
        }
      }
      if (running && crash3DemoPendingLevelCode != 0u &&
          checkpointVblank >=
              crash3DemoPendingLoadVblank + crash3DemoLoadDelayVblanks &&
          !stateCoordinator.pending()) {
        const uint8_t levelCode = crash3DemoPendingLevelCode;
        const std::string path =
            (saveStateDirectory /
             fmt::format("demo_level_{:03}_code_{:02X}_vblank_{}.ps1s",
                         crash3DemoCheckpointIndex, levelCode,
                         checkpointVblank))
                .string();
        if (stateCoordinator.request(ps1::SaveStateCoordinator::Action::Save,
                                     path)) {
          crash3DemoCheckpointLevelCodes.insert(levelCode);
          fmt::print("[SaveState] Crash 3 demo level {} requested at VBlank "
                     "{} (level code 0x{:02X}, resident cohort 0x{:016X})\n",
                     crash3DemoCheckpointIndex, checkpointVblank, levelCode,
                     signal.stable ? signal.activeCohortFingerprint : 0u);
          ++crash3DemoCheckpointIndex;
          crash3DemoPendingLevelCode = 0u;
          crash3DemoCheckpointArmed = false;
        }
      }
    }
    if (exitAfterAutoSave && autoSaveRequested && autoSaveCompleted) {
      fmt::print("[Main] Diagnostic autosave completed\n");
      running = false;
      continue;
    }

    // 2. Consume a bounded slice of host pacing pulses. Hardware advances
    // once per admitted pulse. Any remainder is wall-clock debt, not elapsed
    // guest time, and is coalesced after this slice. This prevents a slow
    // renderer from firing several callbacks before the game reaches its next
    // blocking VSync.
    const uint64_t dueVblanks =
        scheduledVblanks.load(std::memory_order_acquire);
    const auto &pacingState = ps1::psyq::psyq_state();
    const uint32_t currentGuestVblank =
        pacingState.vsyncCounter.load(std::memory_order_acquire);
    const bool guestVblankRequested = ps1::timing::guestVblankRequested(
        pacingState.blockingVSyncPacing.load(std::memory_order_acquire),
        pacingState.blockingVSyncTarget.load(std::memory_order_acquire),
        currentGuestVblank,
        pacingState.autonomousClockWaiters.load(std::memory_order_acquire) +
            (pacingState.cdClockDemand.load(std::memory_order_acquire) ? 1u
                                                                       : 0u));
    const ps1::timing::VblankSlice vblankSlice = ps1::timing::planVblankSlice(
        processedVblanks, guestVblankRequested ? dueVblanks : processedVblanks,
        maxVblanksPerPresent);
    const uint64_t vblankDebt = vblankSlice.debt;
    peakVblankDebt = std::max(peakVblankDebt, vblankDebt);
    ps1::metrics::setState("timing.vblank_debt_at_poll",
                           static_cast<int64_t>(vblankDebt));
    ps1::metrics::setState("timing.vblank_debt_peak",
                           static_cast<int64_t>(peakVblankDebt));
    if (vblankSlice.count > 1) {
      ps1::metrics::count("timing.vblank_catchup_batch");
      ps1::metrics::count("timing.vblank_debt_ticks", vblankSlice.count - 1);
    }
    ps1::metrics::setState("timing.vblank_host_pulses_planned_coalesce",
                           static_cast<int64_t>(vblankSlice.coalesced));
    bool guestAdvanced = false;
    while (processedVblanks < vblankSlice.end) {
      guestAdvanced = true;
      // Do not mutate the CD controller from the SDL/render thread. Crash 3
      // streams multi-sector pages asynchronously and the controller has one
      // sector buffer; concurrent tick/poll publication can overwrite it and
      // skip an LBA. The game thread consumes this credit at safe yields.
      cdromCtrl.accrueClockCycles(guestCyclesPerVblank);
      if (spu.guestClockEnabled())
        spu.accrueSamples(ps1::spu::SAMPLE_RATE / guestRefreshHz);

      uint32_t timerIrqs = 0;
      uint32_t timerIrqCounts[3] = {};
      for (uint32_t scanline = 0; scanline < guestScanlines; ++scanline) {
        const uint32_t cycles =
            baseCyclesPerScanline + (scanline < extraScanlineCycles ? 1u : 0u);
        timerIrqs |= timers.tick(cycles, true, false);
        for (std::size_t timer = 0; timer < 3; ++timer)
          timerIrqCounts[timer] += timers.lastIrqCount(timer);
      }

      static constexpr uint32_t timerBits[3] = {ps1::IRQ_TMR0, ps1::IRQ_TMR1,
                                                ps1::IRQ_TMR2};
      for (std::size_t timer = 0; timer < 3; ++timer) {
        if ((timerIrqs & timerBits[timer]) == 0)
          continue;
        irqCtrl.raiseInterrupt(timerBits[timer]);
        if ((irqCtrl.readIMask() & timerBits[timer]) != 0)
          bios.triggerRootCounterEvents(static_cast<uint32_t>(timer),
                                        timerIrqCounts[timer]);
      }

      auto &timingState = ps1::psyq::psyq_state();
      const uint32_t newCount =
          timingState.vsyncCounter.load(std::memory_order_relaxed) + 1;

      // Latch the completed VRAM and its GP1 display state before publishing
      // the VBlank counter.  Publishing first wakes the game out of VSync;
      // Crash immediately flips PutDispEnv and starts clearing the new back
      // buffer, racing this snapshot and producing a mismatched double buffer.
      gpu.snapshotDisplayBuffer(newCount);
      ps1::metrics::setTraceFrame(newCount);

      if (inputScriptEnabled) inputScript.apply(newCount, input);
      input.latchVBlank();
      if (!mgsProfile) {
        bios.updatePadBuffers();
        ps1::psyq::psyq_pad_refresh_direct_buffers(&ctx);
      }
      // Publish only after the host input snapshot is ready. MGS copies
      // that snapshot into guest pad buffers on its own execution thread.
      irqCtrl.raiseInterrupt(ps1::IRQ_VBLANK);
      timingState.vsyncCounter.store(newCount, std::memory_order_release);
      timingState.pendingVblanks.fetch_add(1, std::memory_order_release);
      if (vblankCounterMirror != 0)
        memory.write32(vblankCounterMirror, newCount);
      ps1::metrics::setState("timing.vblank_index", newCount);
      ps1::metrics::count("timing.vblank");
      ps1::metrics::trace("timing.vblank", {{"index", newCount}});
      if (metricsFlushVblanks != 0 && newCount % metricsFlushVblanks == 0) {
        // Diagnostic checkpoint: a renderer stalled inside a later OT may
        // prevent the normal shutdown path from reacquiring the GPU mutex.
        // Publishing here preserves timing/coverage evidence without being
        // enabled in ordinary runs.
        gpu.publishMetrics();
        ps1::publishPGXPStageMetrics();
        const auto elapsed = std::chrono::steady_clock::now() - hostLoopEpoch;
        ps1::metrics::setState(
            "host.elapsed_us",
            std::chrono::duration_cast<std::chrono::microseconds>(elapsed)
                .count());
        ps1::metrics::dumpJson();
      }
      ++processedVblanks;
      if ((exitVblank != 0 && newCount >= exitVblank) ||
          (exitAfterLoadTarget != 0 && newCount >= exitAfterLoadTarget)) {
        fmt::print("[Main] Diagnostic VBlank {} reached\n", newCount);
        diagnosticExitAfterPresent = true;
        break;
      }
    }

    if (guestAdvanced) {
      // Processing and latching this edge can overlap a later host edge. Keep
      // one such credit for the next safe VSync boundary; retaining a whole
      // backlog would fast-forward guest callbacks, while discarding the first
      // credit creates a full-period slowdown cliff. Re-read after the latch
      // rather than reasoning from the stale `dueVblanks` sampled above.
      const uint64_t scheduledBeforeRebase =
          scheduledVblanks.load(std::memory_order_acquire);
      const ps1::timing::PacingCreditRebase pacingRebase =
          ps1::timing::planPacingCreditRebase(processedVblanks,
                                              scheduledBeforeRebase);
      uint64_t coalesced = 0;
      if (pacingRebase.coalesced != 0) {
        const uint64_t observed = scheduledVblanks.exchange(
            pacingRebase.retainedDue, std::memory_order_acq_rel);
        coalesced =
            ps1::timing::planPacingCreditRebase(processedVblanks, observed)
                .coalesced;
      }
      ps1::metrics::setState("timing.vblank_host_pulses_coalesced_last",
                             static_cast<int64_t>(coalesced));
      if (coalesced != 0)
        ps1::metrics::count("timing.vblank_host_pulses_coalesced", coalesced);
    } else if (!guestVblankRequested && dueVblanks > processedVblanks) {
      // VBlank callbacks must run at a game-thread safe point, but an already
      // elapsed clock edge must not be thrown away merely because VSync is a
      // few microseconds late publishing its target. Keep exactly one credit
      // for that next boundary and coalesce only a true backlog. This removes
      // the former 20 ms performance cliff without ever replaying several
      // callbacks as guest fast-forward.
      const ps1::timing::PacingCreditRebase idleRebase =
          ps1::timing::planPacingCreditRebase(processedVblanks, dueVblanks);
      if (idleRebase.coalesced != 0) {
        const uint64_t scheduledBeforeRebase = scheduledVblanks.exchange(
            idleRebase.retainedDue, std::memory_order_acq_rel);
        const ps1::timing::PacingCreditRebase observedRebase =
            ps1::timing::planPacingCreditRebase(processedVblanks,
                                                scheduledBeforeRebase);
        if (observedRebase.coalesced != 0) {
          ps1::metrics::count("timing.vblank_host_pulses_coalesced",
                              observedRebase.coalesced);
        }
      }
    }

    if (!running)
      break;

    // Other IRQs
    if (cdromCtrl.hasInterrupt()) {
      irqCtrl.raiseInterrupt(ps1::IRQ_CDROM);
      // Event triggering is now handled by the interrupt callback
      // (fired inline from pushResponse), so we only raise the HW IRQ here.
    }
    if (dma.hasInterrupt())
      irqCtrl.raiseInterrupt(ps1::IRQ_DMA);
    if (input.hasInterrupt()) {
      irqCtrl.raiseInterrupt(ps1::IRQ_PAD_MC);
      input.clearInterrupt();
    }
    if (!spu.guestClockEnabled() && spu.hasIrq()) {
      irqCtrl.raiseInterrupt(ps1::IRQ_SPU);
      spu.clearIrq();
    }

    // 3. Render
    if (!diagnosticHeadless && !renderer.processEvents()) {
      running = false;
      continue;
    }
    if (guestAdvanced) {
      if (diagnosticHeadless) {
        // Replay capture is normally configured by RendererVulkan::init(). A
        // future diagnostic may enable it independently; keep this sink here
        // so a presentation-free run can never retain an unbounded frame FIFO.
        while (gpu.tryConsumeReplay()) {
        }
        ps1::metrics::count("host.diagnostic_headless_tick");
      } else {
        renderer.renderFrame();
        ps1::metrics::count("host.present");
      }
      frameCount++;
    } else {
      // Swap interval is not guaranteed (headless drivers and some compositors
      // ignore it). Avoid a busy present loop while waiting for the next
      // guest master-clock edge.
      std::this_thread::sleep_for(std::chrono::microseconds(250));
    }

    if (diagnosticExitAfterPresent)
      running = false;

    // Capture at a chosen frame, not only at shutdown: the game clears VRAM
    // every frame, so a shutdown-only dump always catches it freshly wiped.
    //
    // The threshold counts VBlanks, not iterations of this loop.  This loop is
    // paced by the SDL renderer's vsync and varies with the compositor, while
    // the game thread advances only on the configured PAL/NTSC master clock.
    // Anchoring on
    // frameCount therefore captured a different point of the intro on every
    // run -- sometimes the logo screen, sometimes the black gap after it --
    // which is what made the golden frame look non-deterministic.
    if (const char *atFrame = std::getenv("PS1_VRAM_DUMP_FRAME")) {
      const uint32_t vblanks =
          ps1::psyq::psyq_state().vsyncCounter.load(std::memory_order_acquire);
      if (!frameDumpWritten && vblanks >= std::strtoul(atFrame, nullptr, 10)) {
        const char *path = std::getenv("PS1_VRAM_DUMP_PATH");
        frameDumpWritten =
            dumpVramPpm(gpu, path ? path : "/tmp/vram_frame.ppm");
      }
    }
    if (const char *atFrame = std::getenv("PS1_DISPLAY_DUMP_FRAME")) {
      const uint32_t vblanks =
          ps1::psyq::psyq_state().vsyncCounter.load(std::memory_order_acquire);
      if (!displayFrameDumpWritten &&
          vblanks >= std::strtoul(atFrame, nullptr, 10)) {
        const char *path = std::getenv("PS1_DISPLAY_DUMP_PATH");
        displayFrameDumpWritten =
            dumpDisplayPpm(gpu, path ? path : "/tmp/display_frame.ppm");
      }
    }
    const uint64_t nativeDisplayDumpVblank =
        ps1::psyq::psyq_state().vsyncCounter.load(std::memory_order_acquire);
    if (nativeDisplayDumpRange.selects(nativeDisplayDumpVblank)) {
      const uint64_t vblank = nativeDisplayDumpVblank;
      nativeDisplayDumpRange.lastDumpedVblank = vblank;
      const std::string path = (nativeDisplayDumpRange.directory /
                                fmt::format("frame-{}.ppm", vblank))
                                   .string();
      dumpNativeDisplayPpm(gpu, path.c_str());
    }

    // Status every 5 seconds
    if (guestAdvanced && frameCount % 300 == 0) {
      fmt::print("[Frame {}] I_STAT=0x{:04X} I_MASK=0x{:04X}\n", frameCount,
                 irqCtrl.readIStat(), irqCtrl.readIMask());
    }

    // Check if game thread ended
    if (gameFinished.load(std::memory_order_acquire)) {
      fmt::print("[Main] Game thread finished at frame {}\n", frameCount);
      running = false;
    }

    if (g_shutdown_requested) {
      fmt::print("[Main] Shutdown signal received at frame {}\n", frameCount);
      running = false;
    }

    // Guest pacing comes exclusively from scheduledVblanks. SDL swap interval
    // may additionally block presentation but can never advance emulation.
  }

  if (const char *vramDump = std::getenv("PS1_VRAM_DUMP_PATH")) {
    if (!frameDumpWritten)
      dumpVramPpm(gpu, vramDump);
  }
  if (const char *displayDump = std::getenv("PS1_DISPLAY_DUMP_PATH")) {
    if (!displayFrameDumpWritten)
      dumpDisplayPpm(gpu, displayDump);
  }
  if (const char *spuDump = std::getenv("PS1_SPU_RAM_DUMP_PATH"))
    dumpSpuRam(spu, spuDump);
  if (const char *ramDump = std::getenv("PS1_RAM_DUMP_PATH"))
    dumpMainRam(memory, ramDump);
  const auto elapsed = std::chrono::steady_clock::now() - hostLoopEpoch;
  ps1::metrics::setState(
      "host.elapsed_us",
      std::chrono::duration_cast<std::chrono::microseconds>(elapsed).count());
  if (diagnosticLoadEpoch.has_value()) {
    const auto elapsedAfterLoad =
        std::chrono::steady_clock::now() - *diagnosticLoadEpoch;
    const uint64_t currentVblank =
        ps1::psyq::psyq_state().vsyncCounter.load(std::memory_order_acquire);
    const int64_t elapsedAfterLoadUs =
        std::chrono::duration_cast<std::chrono::microseconds>(elapsedAfterLoad)
            .count();
    const uint64_t vblanksAfterLoad =
        currentVblank >= diagnosticRestoredVblank
            ? currentVblank - diagnosticRestoredVblank
            : 0u;
    ps1::metrics::setState("host.elapsed_after_load_us", elapsedAfterLoadUs);
    ps1::metrics::setState("timing.vblanks_after_load",
                           static_cast<int64_t>(vblanksAfterLoad));
    if (const char *report = std::getenv("PS1_BENCHMARK_REPORT");
        report != nullptr && *report != '\0' && *report != '0') {
      const double rate = elapsedAfterLoadUs > 0
                              ? static_cast<double>(vblanksAfterLoad) *
                                    1'000'000.0 / elapsedAfterLoadUs
                              : 0.0;
      fmt::print("[Benchmark] after load: {} VBlanks in {} us ({:.2f}/s)\n",
                 vblanksAfterLoad, elapsedAfterLoadUs, rate);
      // The recompiled guest can remain inside a polling dispatcher after the
      // host has reached its diagnostic frame bound.  That shutdown path uses
      // _Exit() deliberately, so flush this opt-in report before joining the
      // guest thread instead of losing it with the buffered stdout stream.
      std::fflush(stdout);
    }
  }
  // The last two asynchronous diagnostic copies may not have reached their
  // normal FrameContext-reuse point yet. Drain only their owning fences so the
  // final metrics dump contains every selected latch.
  if (!diagnosticHeadless)
    renderer.drainReplayDiagnostics();
  gpu.publishMetrics();
  ps1::publishPGXPStageMetrics();
  ps1::metrics::dumpJson();

  // Cleanup

  // Wait for game thread (with timeout)
  stateCoordinator.cancel();
  if (gameThread.joinable()) {
    gameFinished.store(true, std::memory_order_release); // shutdown signal
    auto deadline = std::chrono::steady_clock::now() + std::chrono::seconds(2);
    while (!gameThreadDone.load(std::memory_order_acquire) &&
           std::chrono::steady_clock::now() < deadline) {
      std::this_thread::sleep_for(std::chrono::milliseconds(10));
    }
    if (gameThreadDone.load(std::memory_order_acquire)) {
      gameThread.join(); // lambda returned -- safe to join
    } else {
      // Game thread is still inside `recomp_dispatch` (recompiled MIPS is a
      // tight polling loop that does not check `gameFinished`).  Detaching
      // and letting destructors run is UB -- the thread will be reading
      // `Bios::cdEventQueue_` etc. while we destruct them.  Skip C++
      // destructors entirely and exit immediately; the OS will reclaim
      // memory and SDL/audio handles.
      fmt::print("[Main] Game thread did not finish in 2s -- forcing exit "
                 "(skipping destructors to avoid UAF race)\n");
      fmt::print("Simulation ended after {} frames.\n", frameCount);
      // Re-publish: the game thread kept issuing GP0 words during the 2s
      // deadline above.  publishMetrics() only hands over what has accrued
      // since the call before the join, so this adds those words without
      // doubling the ones already reported.
      gpu.publishMetrics();
      ps1::publishPGXPStageMetrics();
      ps1::metrics::dumpJson();
      std::_Exit(0);
    }
  }

  // Join vblank ticker (gameFinished is already set above, so it will exit)
  if (vblankThread.joinable())
    vblankThread.join();

  if (audioDevice > 0) {
    SDL_CloseAudioDevice(audioDevice);
  }
  if (gamepad) {
    SDL_GameControllerClose(gamepad);
  }
  if (!diagnosticHeadless)
    renderer.destroy();
  SDL_Quit();

  fmt::print("Simulation ended after {} frames.\n", frameCount);
  return 0;
}
