// SDL2 Audio Callback
static ps1::spu::SPU *g_spu = nullptr;
static int g_audioVolume = 100;
static bool g_audioMute = false;

// Forward declaration -- generated by ps1Recomp in recompiled_out.cpp
extern void recomp_init_dispatch_table();
extern void recomp_resume_dispatch(uint8_t *rdram, recomp_context *ctx,
                                   uint32_t addr);

static void audioCallback(void * /*userdata*/, uint8_t *stream, int len) {
  if (!g_spu) {
    std::memset(stream, 0, len);
    return;
  }
  uint32_t numSamples = len / (2 * sizeof(int16_t)); // stereo S16
  auto *samples = reinterpret_cast<int16_t *>(stream);
  g_spu->generateSamples(samples, numSamples);
  if (g_audioMute) {
    std::memset(stream, 0, len);
  } else if (g_audioVolume < 100) {
    const int scalar = std::max(0, g_audioVolume);
    for (uint32_t i = 0; i < numSamples * 2; ++i)
      samples[i] =
          static_cast<int16_t>(static_cast<int32_t>(samples[i]) * scalar / 100);
  }
}

static uint16_t buttonFromName(std::string name) {
  using namespace ps1::input;
  std::transform(name.begin(), name.end(), name.begin(),
                 [](unsigned char c) { return std::tolower(c); });
  static const std::unordered_map<std::string, uint16_t> buttons{
      {"select", BTN_SELECT},
      {"l3", BTN_L3},
      {"r3", BTN_R3},
      {"start", BTN_START},
      {"up", BTN_UP},
      {"right", BTN_RIGHT},
      {"down", BTN_DOWN},
      {"left", BTN_LEFT},
      {"l2", BTN_L2},
      {"r2", BTN_R2},
      {"l1", BTN_L1},
      {"r1", BTN_R1},
      {"triangle", BTN_TRIANGLE},
      {"circle", BTN_CIRCLE},
      {"cross", BTN_CROSS},
      {"square", BTN_SQUARE},
  };
  const auto it = buttons.find(name);
  return it == buttons.end() ? 0 : it->second;
}

static std::unordered_map<SDL_Keycode, uint16_t>
makeKeyboardMap(const ps1::InputConfig &config) {
  std::unordered_map<SDL_Keycode, uint16_t> result;
  for (const auto &[keyName, buttonName] : config.keyMap) {
    // Keep configuration keys TOML-friendly while accepting SDL's names for
    // multi-word keys (for example, right_shift -> "Right Shift").
    std::string sdlKeyName = keyName;
    std::replace(sdlKeyName.begin(), sdlKeyName.end(), '_', ' ');
    const SDL_Keycode key = SDL_GetKeyFromName(sdlKeyName.c_str());
    const uint16_t button = buttonFromName(buttonName);
    if (key != SDLK_UNKNOWN && button != 0)
      result[key] = button;
  }
  if (!result.empty())
    return result;

  const std::pair<SDL_Keycode, uint16_t> defaults[]{
      {SDLK_UP, ps1::input::BTN_UP},
      {SDLK_DOWN, ps1::input::BTN_DOWN},
      {SDLK_LEFT, ps1::input::BTN_LEFT},
      {SDLK_RIGHT, ps1::input::BTN_RIGHT},
      {SDLK_z, ps1::input::BTN_CROSS},
      {SDLK_x, ps1::input::BTN_CIRCLE},
      {SDLK_a, ps1::input::BTN_SQUARE},
      {SDLK_s, ps1::input::BTN_TRIANGLE},
      {SDLK_q, ps1::input::BTN_L1},
      {SDLK_w, ps1::input::BTN_R1},
      {SDLK_e, ps1::input::BTN_L2},
      {SDLK_r, ps1::input::BTN_R2},
      {SDLK_RETURN, ps1::input::BTN_START},
      {SDLK_BACKSPACE, ps1::input::BTN_SELECT},
      {SDLK_RSHIFT, ps1::input::BTN_SELECT},
  };
  result.insert(std::begin(defaults), std::end(defaults));
  return result;
}

static bool inputTraceEnabled() {
  static const bool enabled = [] {
    const char *value = std::getenv("PS1_INPUT_TRACE");
    return value && value[0] != '\0' && std::strcmp(value, "0") != 0;
  }();
  return enabled;
}

static void
mapKeyToButton(SDL_Keycode key,
               const std::unordered_map<SDL_Keycode, uint16_t> &keyboardMap,
               ps1::input::InputController &input, bool pressed) {
  const auto it = keyboardMap.find(key);
  if (it == keyboardMap.end())
    return;
  const uint16_t btn = it->second;
  if (pressed)
    input.press(btn, 0);
  else
    input.release(btn, 0);
  if (inputTraceEnabled()) {
    fmt::print("[InputTrace] SDL {} '{}' -> PS1 0x{:04X}, state=0x{:04X}\n",
               pressed ? "down" : "up", SDL_GetKeyName(key), btn,
               input.buttonState(0));
  }
}

