    return BTN_START;
  case SDL_CONTROLLER_BUTTON_LEFTSTICK:
    return BTN_L3;
  case SDL_CONTROLLER_BUTTON_RIGHTSTICK:
    return BTN_R3;
  case SDL_CONTROLLER_BUTTON_LEFTSHOULDER:
    return BTN_L1;
  case SDL_CONTROLLER_BUTTON_RIGHTSHOULDER:
    return BTN_R1;
